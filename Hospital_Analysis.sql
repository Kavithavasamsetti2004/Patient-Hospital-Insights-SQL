-- Queries
select * from patients;
select * from appointments;

-- Total No.of Patients
select count(patient_id) as Total_patients 
		from patients;

-- Total No.of male and female patients (Patients Categorized by gender)
select count(patient_id) as male_patients from patients where gender = 'Male';
select count(patient_id) as female_patients from patients where gender = 'Female';

-- No of doctors
select count(distinct doctor_name) as Total_doctors 
		from appointments;

-- Average Consultancy fee
select avg(consultation_fee) as Avg_Consultation_Fee 
		from appointments;

-- Minimum Consultancy fee
select min(consultation_fee) as Min_consultancy_fee 
		from appointments;
        
-- Max Consultancy fee 
select max(consultation_fee) as Max_consultancy_fee
		from appointments;

-- No.of patients city wise
select city,count(patient_id) as No_of_patients from patients group by city ;

-- No.of Doctors Department wise
select department,
		count(distinct doctor_name) as Total_doctors 
		from appointments 
        group by department
        order by Total_doctors;

-- Average age of patients
select round(avg(timestampdiff(YEAR,date_of_birth,curdate()))) 
		as avg_age 
		from patients;

-- Max No.of Patients Caterorized by age
 select timestampdiff(YEAR,date_of_birth,curdate()) as age,
				count(patient_id) as count 
                from patients
				group by timestampdiff(YEAR,date_of_birth,curdate()) 
                order by count(patient_id) desc
                limit 1;

-- Max no.of appointments for particular doctor
select doctor_name,count(appointment_id) as appointments_count 
		from appointments 
        group by doctor_name
        order by count(appointment_id) desc
        limit 1;
        
-- Average appointments for doctor per day
select appointment_date,doctor_name,count(appointment_id) as total_appointments 
		from appointments 
        group by appointment_id
        order by count(appointment_id);

-- Citywise female patients & male patients & total patients
select city,
        sum(case when gender = 'Male' then 1 else 0 end) as male_patients,
        sum(case when gender = 'Female' then 1 else 0 end) as female_patients,
        count(patient_id) as total_patients
        from patients
        group by city
        order by total_patients;

-- Average no.of appointments every month
select appointment_year,
		appointment_month,
		COUNT(*) AS total_appointments
from(select
        YEAR(appointment_date) AS appointment_year,
        MONTH(appointment_date) AS appointment_month
    FROM appointments
) AS monthly_data
GROUP BY appointment_year, appointment_month
ORDER BY appointment_year, appointment_month;

-- Total consultancy fee generated by each department
select department,
		sum(consultation_fee) as department_revenue
		from appointments 
        group by department;

-- appointments where the consultation fee was greater than ₹800
select appointment_id ,
		consultation_fee from appointments 
        where consultation_fee>800 ;

-- Top 5 cities having the highest number of registered patients
select city,count(patient_id) as No_of_Patients 
			from patients 
            group by city 
            order by No_of_patients desc 
            limit 5;

-- Patient-Appointment Details: 
-- Retrieving a list showing patient_id, patient's full name (first_name + last_name), city, doctor_name, and appointment_date
select p.patient_id,
		concat(p.first_name," ",p.last_name) as full_name ,
        p.city,
        a.doctor_name,a.appointment_date 
		from patients p 
        inner join appointments a
        on p.patient_id = a.patient_id;

-- City Revenue Insights: 
-- Calculate the total revenue (consultation fees) generated from patients residing in each city.
select p.city,
		sum(a.consultation_fee) as total_revenue 
        from patients p 
        inner join appointments a 
		on p.patient_id = a.patient_id 
        group by city;

-- Age Group Analysis: Calculate the current age of each patient and categorize them into age brackets 
-- (e.g., Under 30, 30-35, Above 35) to count total patients in each group.
select case
			when timestampdiff(YEAR,date_of_birth,curdate()) < 30 then 'Under 30'
			when timestampdiff(YEAR,date_of_birth,curdate()) between 30 and 35 then 'Between 30 to 35'
			ELSE 'Above 35'
        end as age_group ,
        count(patient_id) as total_patients from patients
        group by age_group;
        

-- Zero-Appointment Patients: Identify patients who have registered in the patients table but have never booked an appointment.
select p.patient_id,p.first_name from patients p left join appointments a 
		on a.patient_id = p.patient_id where a.appointment_id is null;

-- Doctor Workload: Find the top 3 doctors who have handled the highest number of patient consultations.
select doctor_name,
		count(appointment_id) as total_consultations 
        from appointments 
		group by doctor_name
		order by total_consultations desc 
		limit 3;

-- patients who have booked more than 1 appointment in total
select p.patient_id,concat(p.first_name,' ',p.last_name) as full_name,count(a.appointment_id) as total_appointment_count
		from patients p join appointments a 
        on p.patient_id = a.patient_id
        group by p.patient_id,p.first_name,p.last_name
        having total_appointment_count>1;

-- Department Average vs. Individual Fee
-- Show each appointment's appointment_id, department, and consultation_fee alongside the average consultation fee of that specific department.
select appointment_id,department,consultation_fee,
		avg(consultation_fee) over(partition by department) as average_consultation
		from appointments;
	
-- Patient Spending Rank
-- Calculate the total consultation spending per patient and rank the patients 
-- from highest spender to lowest spender. Display patient_id, full name, total_spent, and their spending_rank
select p.patient_id,concat(p.first_name,' ',p.last_name) as full_name,
		sum(a.consultation_fee) as total_spent,
        dense_rank() over (order by sum(a.consultation_fee) desc ) as spending_rank
        from patients p join appointments a
        on p.patient_id = a.patient_id
        group by patient_id;

WITH MonthlyRevenue AS (
    SELECT 
        DATE_FORMAT(appointment_date, '%Y-%m') AS revenue_month,
        SUM(consultation_fee) AS monthly_revenue
    FROM appointments
    GROUP BY DATE_FORMAT(appointment_date, '%Y-%m')
)
SELECT 
    revenue_month,
    monthly_revenue,
    SUM(monthly_revenue) OVER (ORDER BY revenue_month) AS running_total_revenue
FROM MonthlyRevenue;

-- Step 1: Base View Creation
CREATE VIEW vw_city_department_summary AS
SELECT 
    p.city,
    a.department,
    COUNT(a.appointment_id) AS total_appointments,
    SUM(a.consultation_fee) AS total_department_revenue
FROM patients p
JOIN appointments a ON p.patient_id = a.patient_id
GROUP BY p.city, a.department;

-- Step 2: Ranking Query using CTE on View
WITH DepartmentRanking AS (
    SELECT 
        city,
        department,
        total_appointments,
        total_department_revenue,
        DENSE_RANK() OVER (PARTITION BY city ORDER BY total_appointments DESC) AS dept_rank
    FROM vw_city_department_summary
)
SELECT 
    city,
    department,
    total_appointments,
    total_department_revenue,
    dept_rank
FROM DepartmentRanking
WHERE dept_rank = 1;

-- Citywise High-Value Patient Rate
SELECT 
    p.city,
    COUNT(DISTINCT p.patient_id) AS total_patients,
    COUNT(a.appointment_id) AS total_visits,
    ROUND(COUNT(a.appointment_id) / COUNT(DISTINCT p.patient_id), 2) AS avg_visits_per_patient
FROM patients p
JOIN appointments a ON p.patient_id = a.patient_id
GROUP BY p.city
ORDER BY avg_visits_per_patient DESC;




